`timescale 1ns/1ps
// TC-F11: readiness/abort/recovery with actual CONV_DMA and DDR backend.
// Fault shims are on the RAM-model AXI boundary; they do not drive DUT internals.
module tb_ready_recovery;
 // 修改记录 2026-10-11：加入随机种子激励。
 `include "rtds_random.svh"   // 2026-10-11：随机种子回归：改变激励时序或数据，保留原检查判据
 rtds_real_harness H();logic[31:0] value;int failed_checks=0;
 bit fresh_check=0;int fresh_beats=0,fresh_errors=0;
 always @(posedge H.uclk) if(fresh_check && H.tx_valid && H.tx_ready) begin
   if(H.tx_data!==H.tx_pattern(fresh_beats)) begin
     fresh_errors++;
     $display("CHECK FAIL RECOVERY/STALE_DATA beat=%0d got=%h fresh_expected=%h",fresh_beats,H.tx_data,H.tx_pattern(fresh_beats));
   end
   fresh_beats++;
 end
 task automatic no_access;
   H.read_requests=0;H.read_beats=0;H.command('h8000,16);H.wait_end();
   if(H.read_requests || H.read_beats) $fatal(1,"RECOVERY/NOT_READY_ACCESS");
 endtask
 task automatic interrupt_and_recover(input int kind,input int length);
   bit cleanup=0;   // 2026-10-11：标记是否做过失败清理复位，避免误记无复位恢复
   H.prepare_tx('h8000,length,'h550000,1);H.check_tx=0;H.hold_r=1;
   H.command('h8000,length);wait(H.fdma_rbusy && H.b_rvalid);
   @(negedge H.clk);
   case(kind) 0:H.channel_up=0;1:H.pcie_up=0;2:H.ddr_reset_n=0;endcase
   repeat(200+phase2_pick(0,80)) @(negedge H.clk);H.check_reg('h20,0);   // 2026-10-11：随机种子回归：改变激励时序或数据，保留原检查判据
   H.hold_r=0;
   case(kind) 0:H.channel_up=1;1:H.pcie_up=1;2:H.ddr_reset_n=1;endcase
   repeat(500) @(negedge H.clk);
   if(H.fdma_rbusy) begin
     failed_checks++;
     $display("CHECK FAIL RECOVERY/OLD_READ_STUCK kind=%0d state=%0d old_busy=1 register_busy=0 reset_required=1",kind,H.U_DMA.read_curr_st);
     H.prepare_tx('h9000,32,'h660000+kind*4096,2);
     fresh_beats=0;fresh_errors=0;fresh_check=1;
     H.command('h9000,32);repeat(2000) @(negedge H.clk);H.rd('h20,value);fresh_check=0;
     if(value!=0 || fresh_errors || fresh_beats!=4) begin
       failed_checks++;
       $display("CHECK FAIL RECOVERY/FRESH_TASK kind=%0d busy=%0d fresh_beats=%0d stale_beats=%0d",kind,value,fresh_beats,fresh_errors);
     end
     // Continue independent checks after reporting the failed reset-free recovery.
     // This reset is an explicit test cleanup, not counted as a recovery PASS.
     cleanup=1;H.reset();   // 2026-10-11：只在失败后复位以继续独立检查
     $display("RECOVERY_FAILURE_CLEANUP kind=%0d reset=1",kind);   // 2026-10-11：随机种子回归：改变激励时序或数据，保留原检查判据
   end
   H.valid_tx('h9000,32,'h660000+kind*4096,2);
   repeat(300) @(negedge H.clk);
   if(H.done_events!=1 || H.tx_beats!=4) $fatal(1,"RECOVERY/OLD_COMPLETION");
   if(cleanup) $display("CLEANUP_RESET_CHECK kind=%0d",kind);   // 2026-10-11：失败清理单独记录
   else $display("RECOVERY_NO_RESET_CHECK kind=%0d interrupted_bytes=%0d fresh_beats=4 completion=1",kind,length);   // 2026-10-11：随机种子回归：改变激励时序或数据，保留原检查判据
 endtask
 initial begin
   H.reset(0);repeat(100) @(negedge H.clk);H.check_reg('h2c,0);no_access();
   H.ddr_reset_n=1;repeat(100) @(negedge H.clk);H.rd('h10,value);repeat(100) @(negedge H.clk);H.check_reg('h2c,3);
   H.pcie_up=0;repeat(100) @(negedge H.clk);no_access();H.pcie_up=1;
   H.channel_up=0;repeat(100) @(negedge H.clk);no_access();H.channel_up=1;repeat(100) @(negedge H.clk);
   interrupt_and_recover(0,16);interrupt_and_recover(1,64);interrupt_and_recover(2,32);
   // R SLVERR generated by an out-of-range address at the model boundary.
   H.reset();H.prepare_tx('h8000,16,'h700000,1);H.fault_read=1;H.command('h8000,16);H.wait_end();
   H.check_reg('h2c,7);H.fault_read=0;H.rd('h10,value);repeat(100) @(negedge H.clk);H.check_reg('h2c,3);
   // B SLVERR: no successful length is published; two words are counted as lost.
   H.fault_write=1;H.send_rx(111);H.send_rx(222);repeat(2500) @(negedge H.clk);
   H.check_reg('h2c,7);if(H.ready_blocks || H.dropped_words!=2) $fatal(1,"RECOVERY/B_ERROR_PUBLISHED");
   H.fault_write=0;H.rd('h10,value);repeat(100) @(negedge H.clk);H.check_reg('h2c,3);
   // Delayed R response: DDR/FDMA timeout is reported and clears through real 0x10.
   H.prepare_tx('h8000,16,'h800000,3);H.hold_r=1;H.command('h8000,16);
   repeat(400) @(negedge H.clk);H.check_reg('h2c,19);
   H.hold_r=0;H.wait_end();H.rd('h10,value);repeat(100) @(negedge H.clk);H.check_reg('h2c,3);
   // Stall B to fill the real 2048-word RX FIFO and generate true overflow.
   H.reset();H.hold_b=1;H.send_rx(1);H.send_rx(2);wait(H.b_bvalid);
   for(int i=0;i<2200;i++) H.send_rx('h9000+i);
   repeat(100) @(negedge H.clk);H.rd('h2c,value);
   if(value[31:5]!=0 || !value[3] || !value[4] || value[2:0]!=3) $fatal(1,"RECOVERY/OVERFLOW_STATUS %h",value);
   H.hold_b=0;repeat(50000) @(negedge H.clk);
   H.rd('h10,value);repeat(300) @(negedge H.clk);H.check_reg('h2c,3);
   H.valid_tx('ha000,16,'h990000,4);
   if(failed_checks==0) $display("TEST PASS tb_ready_recovery not_ready=DDR,PCIe,Aurora aborts=3 R_error=1 B_error=1 timeout=1 overflow=1 clear=0x10");
   else $fatal(1,"TEST FAIL tb_ready_recovery failed_checks=%0d",failed_checks);   // 2026-10-11：随机种子回归：改变激励时序或数据，保留原检查判据
   $finish;
 end
 initial begin #4000000;$fatal(1,"RECOVERY/WATCHDOG");end
endmodule
